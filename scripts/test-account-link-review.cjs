const { readFileSync } = require('node:fs');
const { resolve } = require('node:path');
const assert = require('node:assert/strict');
const ts = require('../apps/web/node_modules/typescript');
const source = readFileSync(resolve(__dirname, '../apps/web/src/lib/data/account-link-review.ts'), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const api = { exports: {} };
new Function('exports', 'module', compiled)(api.exports, api);
const { reviewAccountLink, validateAccountLink } = api.exports;
const accounts = [{ id: 'A', name: 'A', email: 'a@example.test', role: 'admin', maNV: 'NV001' }, { id: 'B', name: 'B', email: 'b@example.test', role: 'sewing', maNV: null }];
const employees = [{ maNV: 'NV001', hoTen: 'A' }, { maNV: 'NV002', hoTen: 'B' }];
assert.equal(reviewAccountLink(accounts[0], accounts, employees), 'Đã liên kết');
assert.equal(reviewAccountLink(accounts[1], accounts, employees), 'Chưa liên kết');
assert.doesNotThrow(() => validateAccountLink('B', 'NV002', accounts, employees));
assert.throws(() => validateAccountLink('B', ' nv001 ', accounts, employees), /tài khoản khác/);
assert.throws(() => validateAccountLink('B', 'NV003', accounts, employees), /mã duy nhất/);
assert.throws(() => validateAccountLink('missing', 'NV002', accounts, employees), /không còn tồn tại/);
assert.throws(() => validateAccountLink('B', 'NV002', accounts, [...employees, employees[1]]), /mã duy nhất/);
assert.equal(reviewAccountLink(accounts[0], [...accounts, { ...accounts[1], maNV: 'nv001' }], employees), 'Trùng liên kết tài khoản');
assert.equal(reviewAccountLink(accounts[0], accounts, []), 'Không tìm thấy hồ sơ');
assert.equal(reviewAccountLink(accounts[0], accounts, [...employees, employees[0]]), 'Trùng mã nhân viên');
assert.equal(accounts[1].maNV, null);
console.log('PASS: 11 account-link checks; no database writes.');
